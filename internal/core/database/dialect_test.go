// TestRewriteDML 改写器对查询层 SQL 形态的等价改写。
func TestRewriteDML(t *testing.T) {
	cases := []struct {
		name, in, want string
	}{
		{"占位符重编号", `SELECT * FROM go_modules WHERE id = ? AND path = ?`, `SELECT * FROM go_modules WHERE id = $1 AND path = $2`},
		{"IN 批量占位符", `WHERE module_path IN (?, ?, ?)`, `WHERE module_path IN ($1, $2, $3)`},
		{"LIMIT 参数", `ORDER BY id LIMIT ? OFFSET ?`, `ORDER BY id LIMIT $1 OFFSET $2`},
		{"LIKE 转 ILIKE", `WHERE p.pkg_name LIKE ? ESCAPE '\'`, `WHERE p.pkg_name ILIKE $1 ESCAPE '\'`},
		{"字符串内关键字不动", `SELECT '?LIKE x' FROM go_modules WHERE a = ?`, `SELECT '?LIKE x' FROM go_modules WHERE a = $1`},
		{"注释内关键字不动", "SELECT a -- LIKE ? 注释\nFROM go_modules WHERE a = ?", "SELECT a -- LIKE ? 注释\nFROM go_modules WHERE a = $1"},
		{"CURRENT_TIMESTAMP 转 UTC 格式化",
			`UPDATE go_status SET updated_at = CURRENT_TIMESTAMP WHERE id = 1`,
			`UPDATE go_status SET updated_at = ` + pgNowExpr + ` WHERE id = 1`},
		{"SUM 补 int8", `SELECT (SELECT COALESCE(SUM(file_size_bytes),0) FROM npm_versions)`,
			`SELECT (SELECT COALESCE(SUM(file_size_bytes)::int8,0) FROM npm_versions)`},
		{"SUM 嵌套括号", `SELECT COALESCE(SUM(CASE WHEN v.x > 0 THEN 1 ELSE 0 END),0) FROM t v`,
			`SELECT COALESCE(SUM(CASE WHEN v.x > 0 THEN 1 ELSE 0 END)::int8,0) FROM t v`},
		{"SUM 后无括号不动", `SELECT SUMMARY FROM t`, `SELECT SUMMARY FROM t`},
		{"upsert 原样", `INSERT INTO go_daily_stats (day) VALUES (?) ON CONFLICT(day) DO UPDATE SET x = excluded.x`,
			`INSERT INTO go_daily_stats (day) VALUES ($1) ON CONFLICT(day) DO UPDATE SET x = excluded.x`},
	}
	for _, c := range cases {
		if got := rewriteForPostgres(c.in); got != c.want {
			t.Errorf("%s:\n got %s\nwant %s", c.name, got, c.want)
		}
	}
}

// TestRewriteDDL 建库 DDL 的双方言等价改写（PG 侧类型映射）。
func TestRewriteDDL(t *testing.T) {
	cases := []struct {
		name, in, want string
	}{
		{"自增主键", `id INTEGER PRIMARY KEY AUTOINCREMENT,`,
			`id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,`},
		{"普通 INTEGER 列升位", `zip_size_bytes INTEGER NOT NULL DEFAULT 0`,
			`zip_size_bytes BIGINT NOT NULL DEFAULT 0`},
		{"无自增主键", `id INTEGER PRIMARY KEY CHECK (id = 1)`,
			`id BIGINT PRIMARY KEY CHECK (id = 1)`},
		{"DATETIME 转 TEXT", `meta_cached_at DATETIME,`, `meta_cached_at TEXT,`},
		{"CURRENT_TIMESTAMP 默认值", `updated_at DATETIME DEFAULT CURRENT_TIMESTAMP`,
			`updated_at TEXT DEFAULT ` + pgNowExpr},
		{"内联注释保留", "meta_ttl INTEGER NOT NULL DEFAULT 120000 -- 毫秒",
			"meta_ttl BIGINT NOT NULL DEFAULT 120000 -- 毫秒"},
		{"部分索引", `CREATE INDEX IF NOT EXISTS i ON go_versions(module_id) WHERE zip_size_bytes > 0`,
			`CREATE INDEX IF NOT EXISTS i ON go_versions(module_id) WHERE zip_size_bytes > 0`},
	}
	for _, c := range cases {
		if got := rewriteForPostgres(c.in); got != c.want {
			t.Errorf("%s:\n got %s\nwant %s", c.name, got, c.want)
		}
	}
}

// TestRewriteAllSchemaComponents 全部组件 DDL 改写后必须包含 PG 身份列与 TEXT 时间列，
// 且不得残留 AUTOINCREMENT / DATETIME / 裸 CURRENT_TIMESTAMP。
func TestRewriteAllSchemaComponents(t *testing.T) {
	for _, c := range schemaComponents {
		for _, ddl := range c.DDL {
			pg := rewriteForPostgres(ddl)
			up := strings.ToUpper(pg)
			if strings.Contains(up, "AUTOINCREMENT") || strings.Contains(up, " DATETIME") {
				t.Errorf("组件 %s DDL 改写后残留方言类型: %s", c.Name, pg)
			}
			if strings.Contains(up, "DEFAULT CURRENT_TIMESTAMP") {
				t.Errorf("组件 %s DDL 改写后残留裸 CURRENT_TIMESTAMP: %s", c.Name, pg)
			}
		}
	}
	// 自增表在 PG 侧应使用 IDENTITY
	joined := ""
	for _, c := range schemaComponents {
		for _, ddl := range c.DDL {
			joined += rewriteForPostgres(ddl) + "\n"
		}
	}
	if got := strings.Count(joined, "GENERATED BY DEFAULT AS IDENTITY"); got != 9 {
		t.Errorf("PG DDL 身份列数量应为 9（8 张生态数据表 + mvn_metadata），实际 %d", got)
	}
}

// TestIsPragma PRAGMA 识别。
func TestIsPragma(t *testing.T) {
	if !isPragma("PRAGMA optimize") || !isPragma("  pragma journal_mode=DELETE") {
		t.Fatal("PRAGMA 语句应被识别")
	}
	if isPragma("SELECT 'PRAGMA x'") || isPragma("UPDATE t SET a = 1") {
		t.Fatal("非 PRAGMA 语句不应被识别")
	}
}

// TestRewriteCacheConsistency 缓存命中与未命中路径结果一致，且容量有界。
func TestRewriteCacheConsistency(t *testing.T) {
	in := `SELECT COALESCE(SUM(zip_size_bytes),0) FROM go_versions WHERE module_id = ? AND path LIKE ?`
	first := rewriteForPostgres(in)
	// 命中缓存路径：结果必须与首次一致
	for i := 0; i < 3; i++ {
		if got := rewriteForPostgres(in); got != first {
			t.Fatalf("缓存路径结果不一致:\n got %s\nwant %s", got, first)
		}
	}
	if rewriteCache[in] != first {
		t.Fatal("缓存应已写入")
	}
	// 容量有界：灌入超限条目后重建，尺寸不超过上限
	for i := 0; i < rewriteCacheMax+50; i++ {
		rewriteForPostgres(fmt.Sprintf("SELECT %d FROM t%d WHERE a = ?", i, i))
	}
	rewriteMu.RLock()
	size := len(rewriteCache)
	rewriteMu.RUnlock()
	if size > rewriteCacheMax {
		t.Fatalf("缓存应保持有界: %d > %d", size, rewriteCacheMax)
	}
}
